// FOR Loop
for(let i = 0; i < 5;  i++) {
    console.log("Count: " + i); //0 to 4
}
 // loop through arry with for
 let numbers =[10,20,30];
 for(let i = 0; i < numbers.length; i++) {
    console.log(numbers[i]);
 }

 // WHILE Loop
 let Count = 0;
 while(Count < 3) {
    console.log("While count: " + Count);
    Count++; 
 }
